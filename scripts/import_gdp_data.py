async def create_gdp_table():
    """创建GDP数据表"""
    db_path = "data/property-ai.db"
    conn = await aiosqlite.connect(db_path)
    
    try:
        await conn.execute('''
            CREATE TABLE IF NOT EXISTS regional_gdp (
                id INTEGER PRIMARY KEY AUTOINCREMENT,
                region_name TEXT,
                year INTEGER,
                gdp_value REAL,
                gdp_unit TEXT DEFAULT '亿元',
                created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
                UNIQUE(region_name, year)
            )
        ''')
        
        await conn.execute('''
            CREATE INDEX IF NOT EXISTS idx_gdp_region ON regional_gdp(region_name)
        ''')
        
        await conn.execute('''
            CREATE INDEX IF NOT EXISTS idx_gdp_year ON regional_gdp(year)
        ''')
        
        await conn.commit()
        print("✅ GDP数据表创建完成")
        
    except Exception as e:
        print(f"❌ 创建失败: {e}")
    finally:
        await conn.close()


async def import_gdp_data():
    """导入GDP数据"""
    db_path = "data/property-ai.db"
    conn = await aiosqlite.connect(db_path)
    
    try:
        count = 0
        for region, years_data in GDP_DATA.items():
            for year, gdp_value in years_data.items():
                await conn.execute('''
                    INSERT OR REPLACE INTO regional_gdp (region_name, year, gdp_value)
                    VALUES (?, ?, ?)
                ''', (region, year, gdp_value))
                count += 1
        
        await conn.commit()
        print(f"✅ 导入 {count} 条GDP数据")
        
    except Exception as e:
        print(f"❌ 导入失败: {e}")
    finally:
        await conn.close()


